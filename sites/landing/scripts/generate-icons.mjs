// Bakes the rest pose of the icons the landing uses out of StaySound's one icon catalogue
// (web/src/icons/stayIcons.ts), so the page never drifts from the app's glyphs.
// Run from the repo root: node sites/landing/scripts/generate-icons.mjs
import { buildSync } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const ROOT = process.cwd();
const KINDS = ['download', 'github'];
const tmp = path.join(ROOT, 'node_modules/.cache/landing-icons.mjs');

fs.mkdirSync(path.dirname(tmp), { recursive: true });
buildSync({
  stdin: {
    contents: "export { drawStayIcon, S_MARK } from './web/src/icons/stayIcons'; export { SvgPen } from './web/src/icons/pens';",
    resolveDir: ROOT,
    loader: 'ts',
  },
  bundle: true,
  format: 'esm',
  outfile: tmp,
});

const { drawStayIcon, SvgPen, S_MARK } = await import(pathToFileURL(tmp).href);
const shapes = {};
for (const kind of KINDS) {
  const pen = new SvgPen();
  drawStayIcon(pen, kind, 0, 1, 0);
  shapes[kind] = pen.shapes;
}

const out = `// Generated by scripts/generate-icons.mjs from web/src/icons/stayIcons.ts. Do not edit.
export interface IconShape { d: string; transform: string; fill?: number; stroke?: number; width?: number; trim?: number }

export const S_MARK = ${JSON.stringify(S_MARK)};

export const ICON_SHAPES = ${JSON.stringify(shapes, null, 2)} satisfies Record<string, IconShape[]>;

export type IconKind = keyof typeof ICON_SHAPES;
`;
fs.writeFileSync(path.join(ROOT, 'sites/landing/app/stayIconShapes.ts'), out);
console.log(Object.entries(shapes).map(([k, v]) => `${k}:${v.length}`).join(' '));
