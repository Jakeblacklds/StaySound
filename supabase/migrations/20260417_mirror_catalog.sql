create table if not exists public.mirror_catalog (
    id bigint generated by default as identity primary key,
    base_url text not null,
    provider text not null check (provider in ('tidal', 'dab')),
    enabled boolean not null default true,
    priority integer not null default 100,
    supports_search boolean not null default true,
    supports_stream boolean not null default true,
    supports_download boolean not null default true,
    status text not null default 'available' check (status in ('available', 'slow', 'unavailable')),
    latency_ms integer,
    last_checked_at timestamptz,
    last_error text,
    created_at timestamptz not null default timezone('utc', now()),
    updated_at timestamptz not null default timezone('utc', now()),
    constraint mirror_catalog_base_url_key unique (base_url)
);

create index if not exists mirror_catalog_provider_priority_idx
    on public.mirror_catalog (provider, enabled, priority);

create index if not exists mirror_catalog_status_idx
    on public.mirror_catalog (status, enabled);

create or replace function public.set_mirror_catalog_updated_at()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = timezone('utc', now());
    return new;
end;
$$;

drop trigger if exists trg_mirror_catalog_updated_at on public.mirror_catalog;
create trigger trg_mirror_catalog_updated_at
before update on public.mirror_catalog
for each row
execute function public.set_mirror_catalog_updated_at();

alter table public.mirror_catalog enable row level security;

drop policy if exists "mirror_catalog_public_read" on public.mirror_catalog;
create policy "mirror_catalog_public_read"
on public.mirror_catalog
for select
to anon, authenticated
using (true);

create or replace view public.mirror_catalog_public as
select
    base_url,
    provider,
    enabled,
    priority,
    supports_search,
    supports_stream,
    supports_download,
    status,
    latency_ms,
    last_checked_at,
    last_error
from public.mirror_catalog
where enabled = true
order by priority asc, base_url asc;

grant select on public.mirror_catalog_public to anon, authenticated;

